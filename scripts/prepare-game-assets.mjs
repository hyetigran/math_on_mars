import sharp from "sharp";
import { readdir, mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

// Preserve approved masters; only trim transparent padding and encode runtime copies.
const root = resolve(import.meta.dirname, "../src/assets");
const records = [];
for (const folder of [
  "items/ammo",
  "items/trinkets",
  "items/healing_loot",
  "ui/masters",
]) {
  for (const name of (await readdir(`${root}/${folder}`))
    .filter((n) => n.endsWith(".png"))
    .sort()) {
    const source = `${folder}/${name}`;
    const id = name.replace(/(_v\d+)?\.png$/, "");
    const { data, info } = await sharp(`${root}/${source}`)
      .ensureAlpha()
      .raw()
      .toBuffer({ resolveWithObject: true });
    let left = info.width,
      top = info.height,
      right = 0,
      bottom = 0;
    for (let y = 0; y < info.height; y++)
      for (let x = 0; x < info.width; x++) {
        if (data[(y * info.width + x) * 4 + 3] > 8) {
          left = Math.min(left, x);
          top = Math.min(top, y);
          right = Math.max(right, x);
          bottom = Math.max(bottom, y);
        }
      }
    left = Math.max(0, left - 3);
    top = Math.max(0, top - 3);
    right = Math.min(info.width - 1, right + 3);
    bottom = Math.min(info.height - 1, bottom + 3);
    const crop = {
      left,
      top,
      width: right - left + 1,
      height: bottom - top + 1,
    };
    const size = folder.startsWith("ui") ? 768 : 256;
    const runtimeFolder = `${folder === "ui/masters" ? "ui" : folder}/runtime`;
    await mkdir(`${root}/${runtimeFolder}`, { recursive: true });
    const output = await sharp(`${root}/${source}`)
      .extract(crop)
      .resize(size, size, { fit: "inside", withoutEnlargement: true })
      .webp({ quality: 90, alphaQuality: 100 })
      .toFile(`${root}/${runtimeFolder}/${id}.webp`);
    records.push({
      id,
      source,
      runtime: `${runtimeFolder}/${id}.webp`,
      crop,
      width: output.width,
      height: output.height,
      bytes: output.size,
    });
  }
}
await writeFile(
  `${root}/runtime-manifest.json`,
  JSON.stringify(records, null, 2) + "\n",
);
for (const [group, prefix] of [
  ["itemAssets", ""],
  ["uiAssets", "ui_"],
]) {
  const entries = records.filter((r) =>
    prefix ? r.id.startsWith(prefix) : !r.id.startsWith("ui_"),
  );
  await writeFile(
    `${root}/${group}.ts`,
    `// Generated by scripts/prepare-game-assets.mjs.\nexport const ${group} = {\n${entries.map((r) => `  ${r.id}: new URL('./${r.runtime}', import.meta.url).href,`).join("\n")}\n} as const;\n`,
  );
}
console.log(
  `Prepared ${records.length} assets (${Math.round(records.reduce((n, r) => n + r.bytes, 0) / 1024)} KiB).`,
);
